#!/usr/bin/env bun
/**
 * build-content-manifest.ts — generates src/generated/dialog-manifest.ts with
 * static imports for every dialog JSON file. Runs at build time.
 *
 * Workers runtime can't use import.meta.glob (esbuild-only), so we materialise
 * the imports into a real file the bundler can see. Output is committed so
 * CI doesn't need this script.
 */
import { readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, basename } from 'node:path';

const SCRIPT_DIR = import.meta.dir;
const DIALOGS_DIR = join(SCRIPT_DIR, '..', 'content', 'dialogs');
const OUT_DIR = join(SCRIPT_DIR, '..', 'src', 'generated');
const OUT_FILE = join(OUT_DIR, 'dialog-manifest.ts');

type Difficulty = 'beginner' | 'intermediate' | 'advanced';

interface DialogEntry {
  scenarioId: string;
  difficulty: Difficulty;
  importName: string;
  filename: string;
}

const files = readdirSync(DIALOGS_DIR).filter((f) => f.endsWith('.json'));
const entries: DialogEntry[] = [];

for (const filename of files) {
  const stem = basename(filename, '.json');
  const m = stem.match(/^(.+?)_(intermediate|advanced)$/);
  let scenarioId: string;
  let difficulty: Difficulty;
  if (m) {
    scenarioId = m[1]!;
    difficulty = m[2] as Difficulty;
  } else {
    scenarioId = stem;
    difficulty = 'beginner';
  }
  const importName = stem.replace(/[^a-zA-Z0-9_]/g, '_');
  entries.push({ scenarioId, difficulty, importName, filename });
}

entries.sort((a, b) => a.importName.localeCompare(b.importName));

const grouped = new Map<string, DialogEntry[]>();
for (const e of entries) {
  if (!grouped.has(e.scenarioId)) grouped.set(e.scenarioId, []);
  grouped.get(e.scenarioId)!.push(e);
}

const importLines = entries.map(
  (e) => `import ${e.importName} from '../../content/dialogs/${e.filename}';`,
);

const mapLines = Array.from(grouped.entries()).map(([scenarioId, list]) => {
  const importNames = list.map((l) => l.importName).join(', ');
  return `  ['${scenarioId}', [${importNames}]],`;
});

const ts = `// AUTO-GENERATED by scripts/build-content-manifest.ts — DO NOT EDIT.
// Regenerate via: bun scripts/build-content-manifest.ts

${importLines.join('\n')}

export const DIALOG_MODULES: Record<string, unknown[]> = [
${mapLines.join('\n')}
] as unknown as Record<string, unknown[]>;
`;

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT_FILE, ts, 'utf-8');

console.log(`[build-content-manifest] wrote ${entries.length} dialogs to ${OUT_FILE}`);
console.log(`[build-content-manifest] grouped under ${grouped.size} scenarios`);
